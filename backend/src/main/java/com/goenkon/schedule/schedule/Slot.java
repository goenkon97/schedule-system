// =====================================================================
// Slot.java：一条排班安排属于哪一「组」
//
//   kitchen  → 厨房正社员（前端 DayEntry.kitchen 里的人）
//   hall     → 服务员正社员（前端 DayEntry.hall 里的人）
//   partTime → 兼职（前端 DayEntry.partTime 里的人）
//
// 为什么需要这一列？
//   前端的一天是分成三个「格子」放人的（kitchen、hall、partTime）。
//   拍平成一行一行以后，格子没有了，必须在每一行上写清楚「这个人原来在哪个格子里」，
//   取出来组装的时候，才能把他放回原来的格子。
//
// 为什么不直接用员工的部门（Department）？
//   「兼职」不是部门，是另一个格子；而且以后可能有「厨房的人临时去帮服务员」这种情况，
//   所以「放在哪个格子」要单独记下来，不能从员工资料里推算。
// =====================================================================

package com.goenkon.schedule.schedule;

public enum Slot {
	// 厨房正社员
	kitchen,
	// 服务员正社员
	hall,
	// 兼职
	partTime
}
