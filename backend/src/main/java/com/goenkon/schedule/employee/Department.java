// =====================================================================
// Department.java：部门（只能是这几个值之一）
//
// enum（枚举）：一种特殊的类，它的「对象」是固定的几个，程序运行期间不会多也不会少。
// 用枚举而不是 String 的好处：
//   - 写成 String 的话，"kitchen"、"Kichen"（拼错）也能存进去，要等出了 bug 才发现；
//   - 写成枚举，只能是 Kitchen 或 Hall，写错了编译就报错，请求里传了别的值 Spring 会直接拒绝。
//
// 命名说明：Java 的习惯是枚举值全大写（KITCHEN），
// 这里故意写成和前端完全一样的 Kitchen / Hall，
// 这样前端发来的 JSON、存进数据库的文字、返回给前端的 JSON 三个地方都是同一个字符串，不用来回转换。
// =====================================================================

// 和 Employee 放在同一个包（employee 功能的所有代码都放在一起）
package com.goenkon.schedule.employee;

// public enum：公开的枚举类型，别的包也能用
public enum Department {
	// 厨房（全部是正社员）
	Kitchen,
	// 服务员 / 大厅（正社员 + 兼职）
	Hall
}
