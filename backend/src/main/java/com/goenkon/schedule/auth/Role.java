// =====================================================================
// Role.java：账号的「角色」—— 决定登录以后能做什么（权限）
//
//   manager → 店长：能增删改员工、做班表、处理员工申请
//   staff   → 员工：只能看自己的信息、看班表、提交申请
//
// 为什么不直接用员工的职位（Position.Manager）来判断权限？
//   职位是「店里的工作分工」，角色是「系统里的权限」，是两件不同的事。
//   现在恰好「职位是店长 = 角色是 manager」，但以后可能会有：
//     - 老板不是员工，但要能管理一切
//     - 某个副店长职位是 Server，但被临时授权排班
//   把权限单独放在账号上，这些情况都不用改员工表的设计。
//   （创建账号时，会按职位自动给出默认角色，见以后的 AccountService）
//
// 和前端 src/auth/AuthContext.ts 里的 role: "manager" | "staff" 一一对应，
// 所以这里也用小写，前后端、数据库三个地方是同一个字符串。
// =====================================================================

// auth 包：放「登录、账号、权限」相关的所有代码（和 employee 包是平级的功能模块）
package com.goenkon.schedule.auth;

// public enum：公开的枚举，只有下面这两个值，程序运行期间不会多也不会少
public enum Role {
	// 店长
	manager,
	// 普通员工
	staff
}
