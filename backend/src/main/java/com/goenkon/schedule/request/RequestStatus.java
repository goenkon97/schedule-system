// =====================================================================
// RequestStatus.java：员工申请的处理状态
//
//   pending → 等待店长处理：员工刚提交，店长还没和他沟通
//   done    → 已沟通：店长当面谈过了，在页面上点了「标记为已沟通」
//
// 申请只是「通知」，系统里不做审批，所以没有「同意 / 拒绝」，只有这两种状态。
// 和前端 src/data/requests.ts 里的 RequestStatus 一模一样。
// =====================================================================

package com.goenkon.schedule.request;

public enum RequestStatus {
	// 等待店长处理（刚提交时都是这个）
	pending,
	// 店长已经当面沟通过了
	done
}
