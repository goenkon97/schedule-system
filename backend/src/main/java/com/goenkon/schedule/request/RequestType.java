// =====================================================================
// RequestType.java：员工申请的类型（只能是这三种之一）
//
//   leave → 请假：有日期（一天，或者一段）
//   swap  → 换班：有日期（想换的那一天），和谁换写在备注里
//   other → 其他：没有日期，只有备注
//
// 为什么用枚举，而不是存一个字符串？
//   存字符串的话，"leave"、"Leave"、"leav"（拼错）都能存进去，要等出 bug 才发现；
//   用枚举，只能是这三个值，前端发来别的值，Jackson 转换时就会失败 → 400。
//
// 值的名字和前端 src/data/requests.ts 里的 RequestType 一模一样，
// 前端发来的 JSON、存进数据库的文字、返回给前端的 JSON，三个地方是同一个字符串，不用转换。
// =====================================================================

// request 包：放「员工申请」这个功能的所有代码（和 employee、auth 平级）
package com.goenkon.schedule.request;

public enum RequestType {
	// 请假
	leave,
	// 换班
	swap,
	// 其他
	other
}
